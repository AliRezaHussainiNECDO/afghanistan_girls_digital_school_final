-- 0050_lesson_learned_tracking.sql — رفع اشکال امنیتی/منطقیِ «قفل زنجیره‌ای
-- درس‌ها با دورزدنِ کار خانگیِ NULL».
--
-- ریشهٔ اشکال: `getLessonLockList`/`checkAndCompleteChapter`/`getChapterList`
-- (backend/src/lib/progress.ts) «تکمیلِ درس» را از روی این دو شرط تصمیم
-- می‌گرفتند: (۱) درس دیده شده (`student_lesson_views`)، (۲) کار خانگیِ آن
-- ارسال/نمره‌داده‌شده — یا اصلاً کار خانگی‌ای برایش وجود نداشته باشد
-- (Fail-safe برای وقتی هوش مصنوعی هنگام ساختِ کار خانگی خطا می‌داد).
--
-- مشکل: کار خانگی *فقط* وقتی ساخته می‌شود که شاگرد خودش دکمهٔ «این درس را
-- یاد گرفتم» را بزند (`POST /lessons/:lessonId/learned`،
-- lib/lessonHomework.ts::autoAssignLessonHomework). یعنی شاگردی که هرگز این
-- دکمه را نمی‌زند (فقط صفحهٔ درس را باز می‌کند و می‌بندد) هم دقیقاً همان
-- وضعیتِ «کار خانگی وجود ندارد» را دارد که Fail-safe بالا برایش طراحی شده
-- بود — یعنی سیستم نمی‌توانست «هرگز یاد نگرفتم» را از «یاد گرفتم ولی هوش
-- مصنوعی خطا داد» تشخیص دهد، و هر دو را «تکمیل‌شده» حساب می‌کرد. نتیجه:
-- شاگرد می‌توانست کل یک فصل/مضمون را فقط با بازکردنِ صفحه‌ها (بدون خواندن،
-- بدون «یاد گرفتم»، بدون کار خانگی) رد کند.
--
-- راه‌حل: این جدول، خودِ رویدادِ «یاد گرفتم» را (جدا از نتیجهٔ ساختِ کار
-- خانگی) مستقیماً ثبت می‌کند؛ از این پس «تکمیلِ درس» علاوه‌بر دیده‌شدن، به
-- وجودِ همین ردیف هم نیاز دارد — و Fail-safeِ «کار خانگی نبود = مشکلی نیست»
-- فقط زمانی اعمال می‌شود که این ردیف وجود داشته باشد (یعنی واقعاً «یاد
-- گرفتم» زده شده و بعد از آن ساختِ کار خانگی شکست خورده).
--
-- توجه: چون طبق درخواستِ صاحب پروژه پیش‌تر یک ریست کامل روی دادهٔ شاگردان
-- انجام شده (هیچ شاگرد واقعی هنوز شروع نکرده)، این مهاجرت هیچ داده‌ای را
-- عقب‌ماندگی (backfill) نمی‌کند — هر شاگردی از این پس با زدنِ «یاد گرفتم»
-- طبیعتاً این جدول را پر می‌کند.
--
-- اجرا:
--   npx wrangler d1 execute afghan_girls_school_db --remote --file=./migrations/0050_lesson_learned_tracking.sql

CREATE TABLE IF NOT EXISTS student_lesson_learned (
  student_id TEXT NOT NULL,
  lesson_id TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  PRIMARY KEY (student_id, lesson_id)
);

CREATE INDEX IF NOT EXISTS idx_lesson_learned_lesson ON student_lesson_learned(lesson_id);
